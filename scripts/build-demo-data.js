import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const scenarioDirectory = path.join(root, "scenarios");
const names = (await readdir(scenarioDirectory)).filter((name) => name.endsWith(".json")).sort();
const policyCache = new Map();
const cases = [];

for (const name of names) {
  const scenario = JSON.parse(await readFile(path.join(scenarioDirectory, name), "utf8"));
  const policyPath = path.resolve(scenarioDirectory, scenario.policy);
  if (!policyCache.has(policyPath)) {
    policyCache.set(policyPath, JSON.parse(await readFile(policyPath, "utf8")));
  }
  cases.push({ file: name, scenario, policy: policyCache.get(policyPath) });
}

const banner = "// Generated by scripts/build-demo-data.js. Do not edit by hand.\n";
const body = `export const DEMO_CASES = ${JSON.stringify(cases, null, 2)};\n`;
await writeFile(path.join(root, "demo", "data.js"), banner + body, "utf8");
process.stdout.write(`Built browser data for ${cases.length} scenarios\n`);
